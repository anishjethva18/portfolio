import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import type { ProjectData } from '../db/database';
import { assertPrivateStoragePath } from '../utils/privateStoragePath';
import { getPortfolioStorageRoot } from '../utils/portfolioStorageRoot';

const GENERATED_MARKER = '<!-- Generated by Windows Portfolio OS; maintained from admin project data. -->';

function safeProjectId(id: string): string {
  const safeId = id.trim();
  if (!safeId || !/^[a-zA-Z0-9_-]+$/.test(safeId)) {
    throw new Error('Project Markdown cannot be stored because the project ID is invalid.');
  }
  return safeId;
}

function markdownForProject(project: ProjectData): string {
  const lines = [
    `# ${project.title}`,
    project.tagline && `> ${project.tagline}`,
    project.category && `**Category:** ${project.category}`,
    project.summary && `## Summary\n${project.summary}`,
    project.overview && `## Overview\n${project.overview}`,
    project.description && `## Description\n${project.description}`,
    project.technologies?.length && `## Technologies\n${project.technologies.map((item) => `- ${item}`).join('\n')}`,
    project.features?.length && `## Features\n${project.features.map((item) => `- ${item}`).join('\n')}`,
    project.caseStudy?.goal && `## Goal\n${project.caseStudy.goal}`,
    project.caseStudy?.approach && `## Approach\n${project.caseStudy.approach}`,
    project.caseStudy?.architecture?.length && `## Architecture\n${project.caseStudy.architecture.map((item) => `- ${item}`).join('\n')}`,
    project.caseStudy?.engineeringHighlights?.length &&
      `## Engineering Highlights\n${project.caseStudy.engineeringHighlights.map((item) => `- ${item}`).join('\n')}`,
    project.caseStudy?.delivered && `## Delivered\n${project.caseStudy.delivered}`,
    project.githubUrl && `## Links\n- [GitHub](${project.githubUrl})`,
    project.liveUrl && `- [Live site](${project.liveUrl})`,
  ].filter((line): line is string => Boolean(line));
  return `${GENERATED_MARKER}\n<!-- portfolio-project-id: ${project.id} -->\n\n${lines.join('\n\n')}\n`;
}

export class ProjectMarkdownStorageService {
  private readonly storageRoot: string;
  private readonly projectDirectory: string;

  constructor(storageRoot = getPortfolioStorageRoot()) {
    this.storageRoot = assertPrivateStoragePath(path.resolve(storageRoot), 'Project Markdown storage root');
    this.projectDirectory = assertPrivateStoragePath(
      path.resolve(this.storageRoot, 'project'),
      'Project Markdown directory',
    );
  }

  public syncProjects(projects: ProjectData[]): void {
    fs.mkdirSync(this.projectDirectory, { recursive: true, mode: 0o700 });
    this.assertContained(this.projectDirectory);
    const ids = projects.map((project) => safeProjectId(project.id));
    if (new Set(ids).size !== ids.length) {
      throw new Error('Project Markdown sync found duplicate project IDs.');
    }

    for (const project of projects) {
      const id = safeProjectId(project.id);
      const destination = this.resolveProjectFile(id);
      if (fs.existsSync(destination)) {
        this.assertOwnedFile(destination, id);
      }
      const temporaryPath = path.join(this.projectDirectory, `.project-${id}-${crypto.randomUUID()}.tmp`);
      try {
        fs.writeFileSync(temporaryPath, markdownForProject(project), { flag: 'wx', mode: 0o600 });
        fs.renameSync(temporaryPath, destination);
      } catch (error) {
        if (fs.existsSync(temporaryPath)) fs.unlinkSync(temporaryPath);
        throw new Error(`Could not update generated Project Markdown for ${id}: ${error instanceof Error ? error.message : 'unknown error'}`);
      }
    }

    const currentIds = new Set(ids);
    for (const entry of fs.readdirSync(this.projectDirectory, { withFileTypes: true })) {
      const match = /^project-([a-zA-Z0-9_-]+)\.md$/.exec(entry.name);
      if (!entry.isFile() || !match || currentIds.has(match[1])) continue;
      const stalePath = path.join(this.projectDirectory, entry.name);
      this.assertOwnedFile(stalePath, match[1]);
      fs.unlinkSync(stalePath);
    }
  }

  private resolveProjectFile(id: string): string {
    const resolved = path.resolve(this.projectDirectory, `project-${id}.md`);
    this.assertContained(resolved);
    return resolved;
  }

  private assertContained(candidate: string): void {
    const canonical = fs.existsSync(candidate) ? fs.realpathSync(candidate) : path.resolve(candidate);
    const relative = path.relative(this.storageRoot, canonical);
    if (
      relative === '' ||
      relative === '..' ||
      relative.startsWith(`..${path.sep}`) ||
      path.isAbsolute(relative)
    ) {
      throw new Error('Project Markdown path is outside private server storage.');
    }
  }

  private assertOwnedFile(filePath: string, id: string): void {
    this.assertContained(filePath);
    if (!fs.statSync(filePath).isFile()) {
      throw new Error(`Project Markdown destination is not a regular file: project-${id}.md`);
    }
    const header = fs.readFileSync(filePath, 'utf8').split(/\r?\n/, 2).join('\n');
    if (header !== `${GENERATED_MARKER}\n<!-- portfolio-project-id: ${id} -->`) {
      throw new Error(`Refusing to overwrite or remove an unowned Project file: project-${id}.md`);
    }
  }
}

export const projectMarkdownStorageService = new ProjectMarkdownStorageService();
